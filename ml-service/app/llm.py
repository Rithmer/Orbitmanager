def _build_user_prompt(task: TaskRiskInput, ml_output: TaskRiskOutput) -> str:
    delay_pct = round(ml_output.delayProbability * 100)
    factors = (
        "\n".join(f"  - {f}" for f in ml_output.riskFactors)
        if ml_output.riskFactors
        else "  — не выявлены"
    )
    status_map = {
        "todo": "не начата",
        "in_progress": "в работе",
        "review": "на ревью",
        "done": "завершена",
        "cancelled": "отменена",
    }
    status_label = status_map.get(str(task.status).lower(), str(task.status))

    return (
        f"Данные задачи:\n"
        f"  Сложность: {task.difficulty}/5\n"
        f"  Статус: {status_label}\n"
        f"  Дней до дедлайна: {task.daysUntilDeadline}\n"
        f"  Исполнителей: {task.assigneeCount}\n"
        f"  Нагрузка исполнителя: {task.assigneeLoad} активных задач\n"
        f"  Изменений статуса: {task.statusChangesCount}\n"
        f"\n"
        f"Результат ML модели:\n"
        f"  Уровень риска: {ml_output.riskLevel}\n"
        f"  Вероятность задержки: {delay_pct}%\n"
        f"  Прогнозная дата завершения: {ml_output.predictedCompletionDate}\n"
        f"  Факторы риска:\n{factors}\n"
        f"\n"
        f"Рекомендация:"
    )


class LlmInterpreter:
    """Calls a local LM Studio model to generate a human-readable recommendation."""

    def __init__(self) -> None:
        self._client = httpx.Client(timeout=LLM_TIMEOUT)

    def interpret(
        self, task: TaskRiskInput, ml_output: TaskRiskOutput
    ) -> Optional[str]:
        """Return LLM-generated recommendation, or None if LLM is disabled/unavailable."""
        if not LLM_ENABLED:
            return None

        messages = [{"role": "system", "content": _SYSTEM_PROMPT}]
        for example_user, example_assistant in _FEW_SHOT_EXAMPLES:
            messages.append({"role": "user", "content": example_user})
            messages.append({"role": "assistant", "content": example_assistant})
        messages.append({"role": "user", "content": _build_user_prompt(task, ml_output)})

        payload = {
            "model": LLM_MODEL,
            "messages": messages,
            "temperature": 0.6,
            "max_tokens": 256,
            "stream": False,
        }

        try:
            response = self._client.post(
                f"{LLM_URL}/chat/completions",
                json=payload,
                headers={"Content-Type": "application/json"},
            )
            response.raise_for_status()
            data = response.json()
            text: str = data["choices"][0]["message"]["content"].strip()
            logger.debug("LLM recommendation generated (%d chars)", len(text))
            return text
        except httpx.TimeoutException:
            logger.warning("LLM request timed out after %.0fs", LLM_TIMEOUT)
        except httpx.HTTPStatusError as e:
            logger.warning("LLM HTTP error %s: %s", e.response.status_code, e.response.text[:200])
        except (KeyError, json.JSONDecodeError) as e:
            logger.warning("LLM response parse error: %s", e)
        except Exception as e:  # noqa: BLE001
            logger.warning("LLM call failed: %s", e)

        return None

    def close(self) -> None:
        self._client.close()


# Singleton
llm_interpreter = LlmInterpreter()
